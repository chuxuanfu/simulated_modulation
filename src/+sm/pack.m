function w = pack(iq,fs,p,scope,details)
if nargin<5, details=struct; end
validateattributes(iq,{'numeric'},{'2d','nonempty','finite'});
validateattributes(fs,{'numeric'},{'scalar','positive','finite'});
assert(size(iq,1)>1,'IQ must be samples-by-channels.');
w = struct('iq',double(iq),'fs',double(fs),'config',p,'details',details);
w.meta = struct('ProjectVersion','1.0.0','Protocol',p.Protocol, ...
    'Scope',scope,'CenterFrequencyHz',p.CenterFrequencyHz, ...
    'SampleRateHz',fs,'NumSamples',size(iq,1),'NumChannels',size(iq,2), ...
    'DurationSec',size(iq,1)/fs,'Seed',p.Seed,'IQConvention','I+jQ', ...
    'RFConvention','real((I+jQ)*exp(+j*2*pi*fc*t))', ...
    'CreatedLocal',datestr(now,30),'MATLABVersion',version);
end
